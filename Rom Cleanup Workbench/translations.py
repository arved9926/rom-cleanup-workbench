# Each language under its own name, for the choice in the settings dialog.
LANGUAGE_NAMES = {"en": "English", "de": "Deutsch", "it": "Italiano", "es": "Español", "fr": "Français", "ja": "日本語"}
# What a file without a known region is called in region_priority; every language's word works.
NO_REGION_WORDS = ("none", "keine", "nessuna", "ninguna", "aucune", "なし")

_current = DEFAULT_LANGUAGE


def set_language(language: str) -> None:
    if language not in LANGUAGES:
        raise ValueError(tr("config.unknown_language", language=language, languages=", ".join(LANGUAGES)))
    global _current
    _current = language


def current_language() -> str:
    return _current


def tr(key: str, /, **values) -> str:
    """The text for key in the current language, filled with values.

    key is positional only, so that a text may itself have a field called "key".
    """
    return LANGUAGES[_current][key].format(**values)
